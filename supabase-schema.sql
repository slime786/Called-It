alter table public.call_flags enable row level security;

-- Public reading: the product is built around public records.
drop policy if exists "profiles public read" on public.profiles;
create policy "profiles public read" on public.profiles for select using (true);
drop policy if exists "calls public read" on public.calls;
create policy "calls public read" on public.calls for select using (true);
drop policy if exists "positions public read" on public.positions;
create policy "positions public read" on public.positions for select using (true);
drop policy if exists "threads public read" on public.threads;
create policy "threads public read" on public.threads for select using (true);

-- Members can edit only their own profile.
drop policy if exists "profile owner update" on public.profiles;
create policy "profile owner update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

-- Calls can be created by the signed-in author. Resolution is intentionally not exposed to browsers yet.
drop policy if exists "member creates own calls" on public.calls;
create policy "member creates own calls" on public.calls for insert to authenticated with check (auth.uid() = author_id);

-- Positions: one per member per call, editable while call is open/challenge.
drop policy if exists "member creates own positions" on public.positions;
create policy "member creates own positions" on public.positions for insert to authenticated
with check (auth.uid() = user_id and exists(select 1 from public.calls c where c.id=call_id and c.status in ('challenge','open')));
drop policy if exists "member updates own positions" on public.positions;
create policy "member updates own positions" on public.positions for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id and exists(select 1 from public.calls c where c.id=call_id and c.status in ('challenge','open')));

-- Ordinary discussion.
drop policy if exists "member creates own threads" on public.threads;
create policy "member creates own threads" on public.threads for insert to authenticated with check (auth.uid() = author_id);

-- Wording flags are private to authenticated users for now.
drop policy if exists "member reads own flags" on public.call_flags;
create policy "member reads own flags" on public.call_flags for select to authenticated using (auth.uid() = user_id);
drop policy if exists "member creates own flag" on public.call_flags;
create policy "member creates own flag" on public.call_flags for insert to authenticated with check (auth.uid() = user_id);

-- Helpful grants (RLS still controls access).
grant usage on schema public to anon, authenticated;
grant select on public.profiles, public.calls, public.positions, public.threads to anon, authenticated;
grant update on public.profiles to authenticated;
grant insert on public.calls, public.positions, public.threads, public.call_flags to authenticated;
grant update on public.positions to authenticated;
grant select on public.call_flags to authenticated;
grant usage, select on all sequences in schema public to authenticated;
